// A structure-aware libFuzzer entry point for animations.
//
// Random mutations rarely keep the frame headers of an animation consistent with its canvas, so
// most inputs would stop in the container parser. This target builds a valid animated file from
// the input instead: the canvas size, and for every frame its position, size, duration, blending,
// disposal and pixels. Most frames are small VP8L images of one color, which always decode, so
// the inputs reach the compositing code. Some frames carry input bytes as their bitstream, which
// exercises failures in the middle of an animation.

import RasterWebPCore
import RasterWebPDecoder

private struct InputReader {
    let bytes: UnsafeBufferPointer<UInt8>
    var position = 0

    var remaining: Int { bytes.count - position }

    mutating func byte() -> UInt8 {
        guard position < bytes.count else {
            return 0
        }
        defer { position += 1 }
        return bytes[position]
    }

    mutating func value(below bound: Int) -> Int {
        Int(byte()) % bound
    }

    mutating func take(_ count: Int) -> [UInt8] {
        (0..<min(count, remaining)).map { _ in byte() }
    }
}

/// Writes a VP8L bitstream, least significant bit first.
private struct BitWriter {
    var bytes: [UInt8] = []
    private var usedBits = 0

    mutating func write(_ value: Int, bits: Int) {
        for bit in 0..<bits {
            if usedBits == 0 {
                bytes.append(0)
            }
            bytes[bytes.count - 1] |= UInt8((value >> bit) & 1) << UInt8(usedBits)
            usedBits = (usedBits + 1) % 8
        }
    }
}

private func littleEndian(_ value: Int, _ count: Int) -> [UInt8] {
    (0..<count).map { UInt8(truncatingIfNeeded: value >> ($0 * 8)) }
}

private func chunk(_ fourCC: String, _ payload: [UInt8]) -> [UInt8] {
    Array(fourCC.utf8) + littleEndian(payload.count, 4) + payload + (payload.count % 2 == 1 ? [0] : [])
}

/// A VP8L image whose pixels all have one ARGB color, or that continues with input bytes.
private func losslessImage(width: Int, height: Int, _ input: inout InputReader) -> [UInt8] {
    var writer = BitWriter()
    writer.write(0x2F, bits: 8)
    writer.write(width - 1, bits: 14)
    writer.write(height - 1, bits: 14)
    writer.write(1, bits: 1)
    writer.write(0, bits: 3)
    if input.value(below: 8) == 0 {
        return writer.bytes + input.take(input.value(below: 64))
    }

    // No transform, no color cache and no meta prefix codes, then five codes of one symbol each:
    // green, red, blue, alpha and distance.
    writer.write(0, bits: 3)
    for _ in 0..<4 {
        writer.write(0b1_0_1, bits: 3)
        writer.write(Int(input.byte()), bits: 8)
    }
    writer.write(0b1_0_0, bits: 3)
    writer.write(0, bits: 1)
    return writer.bytes
}

/// Builds and decodes one animation from the input generated by libFuzzer.
@_cdecl("LLVMFuzzerTestOneInput")
public func fuzzAnimation(_ data: UnsafePointer<UInt8>?, _ count: Int) -> CInt {
    var input = InputReader(bytes: UnsafeBufferPointer(start: data, count: count))
    let canvasWidth = 1 + input.value(below: 64)
    let canvasHeight = 1 + input.value(below: 64)

    var frames: [[UInt8]] = []
    while input.remaining > 0, frames.count < 16 {
        let width = 1 + input.value(below: canvasWidth)
        let height = 1 + input.value(below: canvasHeight)
        let x = input.value(below: (canvasWidth - width) / 2 + 1)
        let y = input.value(below: (canvasHeight - height) / 2 + 1)
        let duration = Int(input.byte())
        let flags = input.byte() & 0x03
        let header =
            littleEndian(x, 3) + littleEndian(y, 3) + littleEndian(width - 1, 3)
            + littleEndian(height - 1, 3) + littleEndian(duration, 3) + [flags]
        frames.append(chunk("ANMF", header + chunk("VP8L", losslessImage(width: width, height: height, &input))))
    }
    guard !frames.isEmpty else {
        return 0
    }

    let canvas = [UInt8(0x12)] + [0, 0, 0] + littleEndian(canvasWidth - 1, 3) + littleEndian(canvasHeight - 1, 3)
    let body = Array("WEBP".utf8) + chunk("VP8X", canvas) + chunk("ANIM", [0, 0, 0, 0, 0, 0]) + frames.joined()
    let file = Array("RIFF".utf8) + littleEndian(body.count, 4) + body

    guard var decoder = try? WebPAnimationDecoder(file) else {
        return 0
    }
    precondition(decoder.frames.count == frames.count)
    let first = try? WebPDecoder.decode(file)
    var index = 0
    while let frame = try? decoder.nextFrame() {
        precondition(frame.image.pixels.count == canvasWidth * canvasHeight * 4)
        precondition(index != 0 || frame.image == first)
        index += 1
    }

    // Decoding again after a reset must give the same first frame.
    decoder.reset()
    if let frame = try? decoder.nextFrame() {
        precondition(frame.image == first)
    }
    return 0
}
