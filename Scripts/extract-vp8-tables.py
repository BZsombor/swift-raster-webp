#!/usr/bin/env python3
"""Extracts the VP8 probability and quantizer tables from the text of RFC 6386.

    python3 Scripts/extract-vp8-tables.py [rfc6386.txt]

Without an argument, the RFC is downloaded from rfc-editor.org. The output replaces
Sources/RasterWebPDecoder/Lossy/VP8Tables.swift.
"""

import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "Sources/RasterWebPDecoder/Lossy/VP8Tables.swift"

TABLES = [
    # (Swift name, C declaration that starts the table, section, expected count, element type, comment)
    ("defaultCoefficientProbabilities", "const Prob default_coeff_probs", "13.5", 4 * 8 * 3 * 11, "UInt8",
     "The default token probabilities, indexed by block type, band, context and tree node."),
    ("coefficientUpdateProbabilities", "const Prob coeff_update_probs", "13.4", 4 * 8 * 3 * 11, "UInt8",
     "The probabilities that each token probability is updated in the frame header."),
    ("keyFrameSubblockModeProbabilities", "const Prob kf_bmode_prob ", "11.5", 10 * 10 * 9, "UInt8",
     "The subblock mode probabilities of key frames, indexed by the modes above and to the left."),
    ("dcQuantizers", "static const int dc_qlookup", "14.1", 128, "UInt16",
     "The DC dequantization factors for each quantizer index."),
    ("acQuantizers", "static const int ac_qlookup", "14.1", 128, "UInt16",
     "The AC dequantization factors for each quantizer index."),
]


def load_text():
    if len(sys.argv) > 1:
        return pathlib.Path(sys.argv[1]).read_text(encoding="utf8")
    with urllib.request.urlopen("https://www.rfc-editor.org/rfc/rfc6386.txt", timeout=60) as response:
        return response.read().decode("utf8")


def body_lines(text):
    """Returns the lines of the narrative part, without page headers and footers."""
    lines = []
    for line in text.split("\n"):
        if line.startswith("20.  Attachment One"):
            break
        if re.match(r"^Bankoski, et al\.", line) or re.match(r"^RFC 6386 +VP8 Data Format", line):
            continue
        lines.append(line.replace("\f", ""))
    return lines


def extract(lines, declaration):
    for start, line in enumerate(lines):
        if declaration in line:
            # Skip declarations without data, such as the one in section 11.3.
            following = " ".join(lines[start:start + 3])
            if "=" not in following:
                continue
            values = []
            depth = 0
            started = False
            for current in lines[start:]:
                text = current.split("/*")[0]
                if "=" in text and not started:
                    text = text.split("=", 1)[1]
                for character in text:
                    if character == "{":
                        depth += 1
                        started = True
                    elif character == "}":
                        depth -= 1
                values += [int(value) for value in re.findall(r"\b\d+\b", text)] if started else []
                if started and depth == 0:
                    return values
    raise SystemExit(f"Table not found: {declaration}")


def main():
    lines = body_lines(load_text())
    output = [
        "// Generated by Scripts/extract-vp8-tables.py from the text of RFC 6386. Do not edit.",
        "",
        "enum VP8Tables {",
    ]
    for name, declaration, section, count, element, comment in TABLES:
        values = extract(lines, declaration)
        if len(values) != count:
            raise SystemExit(f"{name}: expected {count} values, found {len(values)}")
        output.append(f"    /// {comment}")
        output.append("    ///")
        output.append(f"    /// RFC 6386, section {section}.")
        output.append(f"    static let {name}: [{element}] = [")
        for row in range(0, len(values), 16):
            output.append("        " + ", ".join(str(value) for value in values[row:row + 16]) + ",")
        output.append("    ]")
        output.append("")
    output[-1] = "}"
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(output) + "\n", encoding="utf8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
